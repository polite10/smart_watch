"""Generate the puzzle workshop and Snake garden for the existing shared cache.

320x320 RGB565 stretches to the round 480px display. Only one game backdrop
is decoded at a time; no extra framebuffer or GPU configuration is needed.
Requires Pillow and lz4, like generate-flappy-scenery.py.
"""
from pathlib import Path
import sys,math,random,struct
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tmp/art-libs'))
from PIL import Image,ImageDraw,ImageFilter
import lz4.block

def gradient(top,bottom):
    im=Image.new('RGB',(480,480));d=ImageDraw.Draw(im)
    for y in range(480):
        t=y/479;d.line((0,y,479,y),fill=tuple(round(a+(b-a)*t) for a,b in zip(top,bottom)))
    return im

def fern(d,x,y,size,angle):
    a=math.radians(angle);ux,uy=math.cos(a),math.sin(a);vx,vy=-uy,ux
    end=(x+ux*size,y+uy*size)
    d.line((x,y,*end),fill='#78995a',width=2)
    for i in range(1,10):
        t=i/11;cx=x+ux*size*t;cy=y+uy*size*t;reach=size*.25*math.sin(t*math.pi)
        for side in (-1,1):
            tip=(cx+vx*reach*side+ux*9,cy+vy*reach*side+uy*9)
            points=[(cx-ux*5,cy-uy*5),tip,(cx+ux*6+vx*reach*side*.35,cy+uy*6+vy*reach*side*.35)]
            d.polygon(points,fill=['#4c7b46','#69944f','#8da85d'][i%3])
            d.line((cx,cy,*tip),fill='#a8b97a',width=1)

def stone(d,x,y,w,h):
    d.ellipse((x,y+4,x+w,y+h+4),fill='#283c32')
    d.ellipse((x,y,x+w,y+h),fill='#8a9580')
    d.arc((x+2,y+2,x+w-2,y+h-3),185,300,fill='#c0c3a4',width=2)


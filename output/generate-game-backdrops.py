packed=[]
for name,im in [('puzzle',workshop),('snake',garden)]:
    im.save(ROOT/'output'/f'game-backdrop-{name}.png')
    im=im.resize((320,320),Image.Resampling.LANCZOS)
    raw=b''.join(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b in im.get_flattened_data())
    blob=lz4.block.compress(raw,store_size=False)
    assert lz4.block.decompress(blob,uncompressed_size=204800)==raw
    packed.append(blob);print(name,len(blob),'flash bytes')
header='''#ifndef WATCH_GAME_BACKDROPS_H
#define WATCH_GAME_BACKDROPS_H
#include <stdint.h>
enum { WATCH_GAME_BACKDROP_SIZE=320, WATCH_GAME_BACKDROP_BYTES=204800 };
extern const uint8_t *const watch_game_backdrops[2];
extern const uint32_t watch_game_backdrop_sizes[2];
#endif
'''
(ROOT/'App/views/watch_game_backdrops.h').write_text(header)
lines=['/* Generated by output/generate-game-backdrops.py. */','#include "views/watch_game_backdrops.h"']
for i,blob in enumerate(packed):
    lines.append(f'static const uint8_t backdrop_{i}[] __attribute__((aligned(4))) = {{')
    lines.extend(','.join(f'0x{b:02x}' for b in blob[j:j+32])+',' for j in range(0,len(blob),32))
    lines.append('};')
lines+=['const uint8_t *const watch_game_backdrops[2]={backdrop_0,backdrop_1};',
        'const uint32_t watch_game_backdrop_sizes[2]={'+','.join(str(len(b)) for b in packed)+'};']
(ROOT/'App/views/watch_game_backdrops.c').write_text('\n'.join(lines)+'\n')
